/** One `.sqlx` for one mapping. */
export function generateMappingSqlx(
  graph: ObjectGraph,
  mapping: Mapping,
  options: DataformOptions = {},
): DataformFile {
  const model = mapping.model ? graph.modelNamed(mapping.model) : undefined;
  const defaults: Defaults = {
    project: options.project ?? model?.target?.project,
    dataset: options.dataset ?? model?.target?.dataset,
  };

  const target = resolveTable(graph, mapping, mapping.target);
  const dim = mapping.dimensional;
  const name = target?.name ?? mapping.target;
  const schema = target?.dataset ?? defaults.dataset;
  const layer = target?.layer;

  const tags = [...(options.tags ?? []), ...(mapping.stage ? [slug(mapping.stage)] : [])];

  /**
   * Assertions Dataform can run inline.
   *
   * The uniqueness of a dimension's business key is only true *among current rows* once
   * history is kept, and the inline form cannot express that qualifier, so it is claimed
   * only where it actually holds, and the SCD2 case gets a real assertion file instead.
   */
  const uniqueKey = dim?.surrogateKey
    ? [dim.surrogateKey]
    : target?.primaryKey?.length
      ? target.primaryKey
      : undefined;

  const nonNull = target?.columns
    .filter((column) => column.mode === "REQUIRED")
    .map((column) => column.name);

  const body: string[] = [];
  let type: string;
  const config: Record<string, unknown> = {};

  if (mapping.loadStrategy === "declaration") {
    // A declaration has no body at all: it tells Dataform a table exists and is produced
    // elsewhere, which is what makes it referenceable without claiming to build it.
    return {
      path: renderPath(options.paths?.declaration ?? DEFAULT_PATHS.declaration, {
        ...(schema ? { dataset: schema } : {}),
        name,
      }),
      contents:
        (options.header === false ? "" : header(mapping.name, "mapping")) +
        configBlock({ type: "declaration", schema, name }),
      objectId: mapping.id,
      kind: "declaration",
    };
  }

  switch (mapping.loadStrategy) {
    /**
     * SCD2 is operations, not a table or an incremental: the load is two statements and
     * `hasOutput` is what lets the rest of the project still reference it as a table.
     */
    case "scd2": {
      type = "operations";
      config.hasOutput = true;
      body.push(...scd2Statements(mapping, graph, defaults, dim!));
      break;
    }

    /**
     * SCD1 overwrites in place and keeps no history, so it is a straight upsert keyed on
     * the business key, the surrogate key is derived from that key and therefore stable
     * across runs, which is what makes the upsert idempotent.
     */
    case "scd1": {
      type = "incremental";
      config.uniqueKey = dim?.businessKey.length ? dim.businessKey : uniqueKey;
      body.push(withSurrogate(mapping, graph, defaults, dim, false));
      break;
    }

    case "merge": {
      type = "incremental";
      config.uniqueKey = dim?.businessKey.length ? dim.businessKey : uniqueKey;
      body.push(withSurrogate(mapping, graph, defaults, dim, false));
      break;
    }

    case "incremental": {
      type = "incremental";
      if (dim?.surrogateKey) config.uniqueKey = [dim.surrogateKey];
      else if (dim?.businessKey.length) config.uniqueKey = dim.businessKey;
      body.push(withSurrogate(mapping, graph, defaults, dim, true));
      break;
    }

    /**
     * A dated full copy, one per run.
     *
     * Keyed on the snapshot date *plus* the business key so a re-run on the same day
     * replaces that day's copy rather than doubling it, which is the difference between
     * a table you can safely retry and one where a failed run leaves you counting
     * everything twice. Partitioned on the date because every read filters on it.
     */
    case "snapshot": {
      type = "incremental";
      const dateColumn = dim?.snapshotDateColumn ?? "snapshot_date";
      config.uniqueKey = [dateColumn, ...(dim?.businessKey ?? [])];
      body.push(
        selectStatement(mapping, graph, defaults, {
          columns: [`CURRENT_DATE() AS ${ident(dateColumn)}`],
        }),
      );
      // The declared partitioning wins if the table names one; otherwise the snapshot
      // date is the only sensible choice and leaving it unpartitioned is a cost bug.
      if (!target?.partitioning) config.bigquery = { partitionBy: dateColumn };
      break;
    }

    /** Append keeps every row, so it must not carry a uniqueKey, that would upsert. */
    case "append": {
      type = "incremental";
      body.push(withSurrogate(mapping, graph, defaults, dim, true));
      break;
    }

    case "full":
    default: {
      type = "table";
      body.push(withSurrogate(mapping, graph, defaults, dim, false));
      break;
    }
  }

  if (target?.partitioning || target?.clustering?.length) {
    config.bigquery = {
      ...(config.bigquery as Record<string, unknown> | undefined),
      ...(target.partitioning && "field" in target.partitioning && target.partitioning.field
        ? { partitionBy: target.partitioning.field }
        : {}),
      ...(target.clustering?.length ? { clusterBy: target.clustering } : {}),
    };
  }

  // Inline assertions are skipped for SCD2: uniqueness there holds only among current
  // rows, and a bare uniqueKey assertion would fail the moment history exists.
  if (mapping.loadStrategy !== "scd2") {
    const assertions: Record<string, unknown> = {};
    if (uniqueKey?.length) assertions.uniqueKey = uniqueKey;
    if (nonNull?.length) assertions.nonNull = nonNull;
    if (Object.keys(assertions).length > 0) config.assertions = assertions;
  }

  const contents =
    (options.header === false ? "" : header(mapping.name, "mapping")) +
    configBlock({
      type,
      schema,
      name,
      ...(mapping.description ? { description: mapping.description } : {}),
      ...config,
      ...(tags.length > 0 ? { tags } : {}),
    }) +
    "\n" +
    (mapping.customSql ? mapping.customSql.trimEnd() : body.join("\n\n---\n\n")) +
    "\n";

  return {
    path: renderPath(options.paths?.model ?? DEFAULT_PATHS.model, {
      ...(schema ? { dataset: schema } : {}),
      name,
      ...(layer ? { layer } : {}),
    }),
    contents,
    objectId: mapping.id,
    kind: "model",
  };
}

/** The SELECT plus a synthesised surrogate key and, when incremental, the watermark filter. */
function withSurrogate(
  mapping: Mapping,
  graph: ObjectGraph,
  defaults: Defaults,
  dim: DimensionalConfig | undefined,
  incremental: boolean,
): string {
  const extraColumns: string[] = [];

  if (dim?.surrogateKey && dim.surrogateKeyStrategy !== "sourceProvided") {
    const expression = surrogateKeyExpression(dim, businessKeyExpressions(mapping, dim), {
      versioned: false,
    });
    if (expression) extraColumns.push(`${expression} AS ${ident(dim.surrogateKey)}`);
  }

  const select = selectStatement(mapping, graph, defaults, { columns: extraColumns });

  const predicate = incremental ? incrementalWhere(mapping, dim) : undefined;
  if (!predicate) return select;

  /**
   * `when(incremental(), ...)` rather than a plain WHERE.
   *
   * On a first run, or after a full refresh, the target does not exist and
   * `SELECT MAX(...) FROM ${self()}` would fail. Dataform only emits this branch on an
   * incremental run, which is exactly when the table is guaranteed to be there.
   */
  return `${select}\n\${when(incremental(), \`  ${select.includes("WHERE") ? "AND" : "WHERE"} ${predicate}\`)}`;
}

function slug(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_|_$/g, "");
}

/**
 * Declarations for tables this model reads but does not build.
 *
 * Without them Dataform has no node for the source and cannot order the graph, so the
 * pipeline either fails to compile or silently runs before its input is ready.
 */
export function generateDeclarations(
  graph: ObjectGraph,
  modelName: string,
  options: DataformOptions = {},
): DataformFile[] {
  const model = graph.modelNamed(modelName);
  const defaults: Defaults = {
    project: options.project ?? model?.target?.project,
    dataset: options.dataset ?? model?.target?.dataset,
  };

  const mappings = graph
    .inModel(modelName)
    .filter((entry) => entry.object.kind === "mapping")
    .map((entry) => entry.object as Mapping);

  const produced = new Set<string>();
  for (const mapping of mappings) {
    const target = graph.resolve(mapping.target, { model: modelName, kind: "table" })?.target.object;
    if (target) produced.add(target.id);
  }

  const files: DataformFile[] = [];
  const seen = new Set<string>();

  for (const mapping of mappings) {
    for (const source of mapping.sources) {
      const table = resolveTable(graph, mapping, source.ref);
      if (!table || produced.has(table.id) || seen.has(table.id)) continue;
      seen.add(table.id);

      const schema = table.dataset ?? defaults.dataset;
      files.push({
        path: renderPath(options.paths?.declaration ?? DEFAULT_PATHS.declaration, {
          ...(schema ? { dataset: schema } : {}),
          name: table.name,
        }),
        contents:
          (options.header === false ? "" : header(table.name, "table")) +
          configBlock({ type: "declaration", schema, name: table.name }),
        objectId: table.id,
        kind: "declaration",
      });
    }
  }

  return files;
}

/**
 * Assertion files for rules the inline `assertions:` block cannot express.
 *
 * Two kinds, both of which are real governance rules the model already states:
 *
 *  - **Referential integrity.** BigQuery does not enforce foreign keys, so a modelled
 *    relationship is a claim nobody checks unless something checks it. This is that.
 *  - **SCD2 single-current.** "One current row per business key" is the invariant that
 *    makes a type-2 dimension usable, and it is exactly what a botched merge breaks.
 */
export function generateAssertions(
  graph: ObjectGraph,
  modelName: string,
  options: DataformOptions = {},
): DataformFile[] {
  const model = graph.modelNamed(modelName);
  const defaults: Defaults = {
    project: options.project ?? model?.target?.project,
    dataset: options.dataset ?? model?.target?.dataset,
  };
  const template = options.paths?.assertion ?? DEFAULT_PATHS.assertion;
  const files: DataformFile[] = [];

  for (const entry of graph.inModel(modelName)) {
    if (entry.object.kind !== "table") continue;
    const table = entry.object as Table;

    for (const fk of table.foreignKeys) {
      if (!fk.assert) continue;
      const parent = graph.resolve(fk.references.table, { model: modelName, kind: "table" })?.target
        .object as Table | undefined;
      if (!parent) continue;

      const name = `assert_${fk.name}`;
      const joinOn = fk.columns
        .map((column, index) => `p.${ident(fk.references.columns[index] ?? column)} = c.${ident(column)}`)
        .join("\n  AND ");
      const notNull = fk.columns.map((column) => `c.${ident(column)} IS NOT NULL`).join(" AND ");

      files.push({
        path: renderPath(template, { name }),
        contents:
          (options.header === false ? "" : header(fk.name, "foreign key")) +
          configBlock({ type: "assertion", schema: defaults.dataset, name }) +
          "\n" +
          [
            "-- Every child row must find its parent. BigQuery does not enforce foreign",
            "-- keys, so without this the relationship is a claim nobody checks.",
            "SELECT c.*",
            `FROM ${quoted(qualifiedTableName(table, defaults))} AS c`,
            `LEFT JOIN ${quoted(qualifiedTableName(parent, defaults))} AS p`,
            `  ON ${joinOn}`,
            `WHERE ${notNull}`,
            `  AND p.${ident(fk.references.columns[0] ?? "id")} IS NULL`,
          ].join("\n") +
          "\n",
        objectId: table.id,
        kind: "assertion",
      });
    }
  }

  for (const entry of graph.inModel(modelName)) {
    if (entry.object.kind !== "mapping") continue;
    const mapping = entry.object as Mapping;
    if (mapping.loadStrategy !== "scd2") continue;

    const dim = mapping.dimensional;
    if (!dim || dim.businessKey.length === 0) continue;

    const target = resolveTable(graph, mapping, mapping.target);
    if (!target) continue;

    const currentFlag = dim.currentFlagColumn ?? "is_current";
    const name = `assert_${target.name}_single_current`;
    const keys = dim.businessKey.map(ident).join(", ");

    files.push({
      path: renderPath(template, { name }),
      contents:
        (options.header === false ? "" : header(mapping.name, "mapping")) +
        configBlock({ type: "assertion", schema: defaults.dataset, name }) +
        "\n" +
        [
          "-- A type-2 dimension must have exactly one current row per business key.",
          "-- Two is what a merge that closed nothing looks like; zero is what a merge",
          "-- that closed everything looks like. Both are silent without this.",
          `SELECT ${keys}, COUNT(*) AS current_rows`,
          `FROM ${quoted(qualifiedTableName(target, defaults))}`,
          `WHERE ${ident(currentFlag)} = TRUE`,
          `GROUP BY ${keys}`,
          "HAVING COUNT(*) > 1",
        ].join("\n") +
        "\n",
      objectId: mapping.id,
      kind: "assertion",
    });
  }

  return files;
}

/** Every Dataform file for one physical model. */
export function generateDataform(
  graph: ObjectGraph,
  modelName: string,
  options: DataformOptions = {},
): DataformFile[] {
  const model = graph.modelNamed(modelName);
  if (!model) throw new Error(`no model named \`${modelName}\``);
  if (model.tier !== "physical") {
    throw new Error(
      `\`${modelName}\` is a ${model.tier} model; Dataform is only generated from physical models`,
    );
  }

  const mappings = graph
    .inModel(modelName)
    .filter((entry) => entry.object.kind === "mapping")
    .map((entry) => entry.object as Mapping);

  return [
    ...generateDeclarations(graph, modelName, options),
    ...mappings.map((mapping) => generateMappingSqlx(graph, mapping, options)),
    ...generateAssertions(graph, modelName, options),
  ];
}
