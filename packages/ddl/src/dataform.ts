import {
  changeTrackedColumns,
  qualifiedTableName,
  type ColumnMapping,
  type DimensionalConfig,
  type Mapping,
  type ObjectGraph,
  type Table,
} from "@strata/metamodel";

/**
 * Dataform SQLX generation.
 *
 * **Why this is the feature the tool was missing.** `mapping.ts` has always modelled load
 * strategies, change-detection columns, four surrogate-key strategies, conformed
 * dimensions and point-in-time dimension lookups in full detail, and emitted nothing at
 * all. The README said "those mappings are what will generate the Dataform SQLX" and the
 * generator did not exist, so every warehouse using this tool still hand-wrote the SQL the
 * model already described.
 *
 * That gap matters most exactly where it hurts: SCD2. Hand-writing a slowly-changing
 * dimension merge is where data teams reliably lose weeks, and the bugs, a row that never
 * closes, two current versions of the same customer, a surrogate key that changes on every
 * run, are subtle, expensive and usually found in a report rather than in a test.
 *
 * **The shape of what comes out.** One `.sqlx` per mapping, plus a declaration per source
 * table nobody in this model produces, plus assertion files for the rules the model states
 * but Dataform's inline `assertions:` block cannot express. Everything is a pure function
 * of the model: run it twice on an unchanged model and the bytes are identical, which is
 * what makes it safe to run in CI and trivial to review.
 *
 * **What it deliberately does not do.** It never edits a hand-written file. `customSql` is
 * honoured verbatim when present, because a team that needs SQL this form cannot express
 * should stay in the tool with an escape hatch rather than abandon generation entirely.
 */

export interface DataformFile {
  /** Path relative to the Dataform repo root. */
  path: string;
  contents: string;
  /** The object this file was generated from. */
  objectId: string;
  kind: "declaration" | "model" | "assertion";
}

export interface DataformOptions {
  /** Path templates, matching `DataformConnection.paths`. */
  paths?: {
    declaration?: string;
    model?: string;
    assertion?: string;
  };
  /** Default project, when the model's target does not name one. */
  project?: string;
  /** Default dataset, when neither the table nor the model names one. */
  dataset?: string;
  /** Prepend a "generated, do not edit" header. Default true. */
  header?: boolean;
  /** Tags applied to every generated action, for `dataform run --tags`. */
  tags?: string[];
}

const DEFAULT_PATHS = {
  declaration: "definitions/sources/{dataset}/{name}.sqlx",
  model: "definitions/{layer}/{name}.sqlx",
  assertion: "definitions/assertions/{name}.sqlx",
};

// ---------------------------------------------------------------- helpers

/**
 * Backtick-quote a fully qualified name.
 *
 * Not optional: GCP project ids almost always contain hyphens, and BigQuery parses an
 * unquoted `acme-analytics-prod.dataset.table` as arithmetic. Getting this wrong produces
 * SQL that looks correct and fails against every real project.
 */
function quoted(name: string): string {
  return `\`${name}\``;
}

/**
 * The target table, as Dataform refers to it.
 *
 * **Never wrap this in backticks.** `self()` already expands to a fully qualified
 * *backticked* name, so quoting it again yields ``\`\`project.dataset.table\`\```, which
 * BigQuery rejects outright. Naming it once here is what stops the two spellings drifting
 * apart, and they already had: the incremental predicate used the bare form while every
 * SCD2 statement quoted it, so half the generated SQL was invalid.
 */
const SELF = "${self()}";

/** A bare identifier, quoted only when it is not a plain word. */
function ident(name: string): string {
  return /^[A-Za-z_][A-Za-z0-9_]*$/.test(name) ? name : `\`${name}\``;
}

/**
 * Render a path template.
 *
 * `{layer}` collapses rather than producing an `_unknown` directory, matching how the
 * model layout engine treats a variable that resolves to nothing, a table with no layer
 * should land in `definitions/`, not `definitions/undefined/`.
 */
function renderPath(
  template: string,
  vars: { dataset?: string; name: string; layer?: string },
): string {
  return template
    .replace(/\{dataset\}/g, vars.dataset ?? "")
    .replace(/\{name\}/g, vars.name)
    .replace(/\{layer\}/g, vars.layer ?? "")
    .replace(/\/{2,}/g, "/")
    .replace(/^\//, "");
}

function header(objectName: string, kind: string): string {
  return [
    `-- Generated by strata from the ${kind} \`${objectName}\`.`,
    "-- Edits here are overwritten on the next generate; change the model instead.",
    "",
  ].join("\n");
}

/** JS object literal for a Dataform `config` block. Not JSON, keys are unquoted. */
function configBlock(entries: Record<string, unknown>): string {
  const lines: string[] = [];
  for (const [key, value] of Object.entries(entries)) {
    if (value === undefined) continue;
    if (Array.isArray(value) && value.length === 0) continue;
    lines.push(`  ${key}: ${literal(value)}`);
  }
  return `config {\n${lines.join(",\n")}\n}\n`;
}

function literal(value: unknown): string {
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (Array.isArray(value)) return `[${value.map(literal).join(", ")}]`;
  if (value && typeof value === "object") {
    const inner = Object.entries(value)
      .filter(([, v]) => v !== undefined && !(Array.isArray(v) && v.length === 0))
      .map(([k, v]) => `${k}: ${literal(v)}`);
    return `{ ${inner.join(", ")} }`;
  }
  return "null";
}

// ---------------------------------------------------------------- expressions

/**
 * The SQL producing one target column.
 *
 * An explicit expression wins. Otherwise a single source is a straight passthrough, and
 * anything else is `NULL`, which is deliberate: a column with several sources and no
 * expression is an incomplete mapping, and emitting the first source silently would hide
 * that. `NULL` plus the validator's `mapping/missingColumn` warning is the honest pair.
 */
function columnExpression(cm: ColumnMapping): string {
  if (cm.expression) return cm.expression;
  if (cm.sources.length === 1) return cm.sources[0]!;
  return "NULL";
}

/**
 * The surrogate key expression.
 *
 * `hash` uses `FARM_FINGERPRINT` over the business key, which is deterministic: the same
 * business key produces the same surrogate in dev, in prod and after a full rebuild. That
 * reproducibility is the whole reason to prefer it over a generated id, a warehouse whose
 * surrogate keys change on rebuild cannot be compared against yesterday's copy of itself.
 *
 * `CAST(... AS STRING)` on every part because the business key may be numeric, and
 * `CONCAT` on a mix of types is an error. The `|` separator stops `('a','bc')` and
 * `('ab','c')` hashing alike.
 *
 * For SCD2 the key must identify a *version*, not a business entity, so the validity start
 * joins the hash, otherwise every historical row for one customer shares a surrogate key
 * and the fact table cannot tell them apart.
 */
function surrogateKeyExpression(
  dim: DimensionalConfig,
  businessKeyExpressions: string[],
  options: { versioned: boolean; validFrom?: string },
): string {
  switch (dim.surrogateKeyStrategy) {
    case "uuid":
      return "GENERATE_UUID()";
    case "rowNumber":
      return `ROW_NUMBER() OVER (ORDER BY ${businessKeyExpressions.join(", ")})`;
    case "sourceProvided":
      // The mapping supplies it like any other column; nothing to synthesise.
      return "";
    case "hash":
    default: {
      const parts = [...businessKeyExpressions];
      if (options.versioned && options.validFrom) parts.push(options.validFrom);
      const casted = parts.map((part) => `CAST(${part} AS STRING)`);
      return `FARM_FINGERPRINT(CONCAT(${casted.join(", '|', ")}))`;
    }
  }
}

/** The FROM/JOIN chain for a mapping's sources. */
function fromClause(mapping: Mapping, graph: ObjectGraph, defaults: Defaults): string[] {
  const lines: string[] = [];

  mapping.sources.forEach((source, index) => {
    const table = resolveTable(graph, mapping, source.ref);
    const name = table ? quoted(qualifiedTableName(table, defaults)) : quoted(source.ref);
    const alias = ident(source.alias);

    if (index === 0) {
      lines.push(`FROM ${name} AS ${alias}`);
      return;
    }

    const join = source.join;
    if (!join) {
      // No join condition on a second source is a cross join whether or not anyone
      // intended it. Say so in the SQL rather than emitting a comma join that reads
      // like an oversight.
      lines.push(`CROSS JOIN ${name} AS ${alias}`);
      return;
    }
    lines.push(`${join.type.toUpperCase()} JOIN ${name} AS ${alias} ON ${join.on}`);
  });

  return lines;
}

/**
 * Dimension lookups, which turn a fact's natural keys into surrogate keys.
 *
 * `pointInTime` is the difference between a fact that reports today's customer segment and
 * one that reports the segment as it was when the order was placed. The first is a common
 * and quietly wrong answer, and it is only avoidable if the dimension keeps history, so
 * this joins on the row whose validity window contains the fact's own timestamp rather
 * than on the current row.
 */
function dimensionJoins(
  mapping: Mapping,
  graph: ObjectGraph,
  defaults: Defaults,
): { joins: string[]; columns: string[] } {
  const dim = mapping.dimensional;
  const joins: string[] = [];
  const columns: string[] = [];
  if (!dim || dim.dimensionLookups.length === 0) return { joins, columns };

  const eventTime = dim.watermarkColumn;
  const primary = mapping.sources[0]?.alias ?? "s";

  for (const lookup of dim.dimensionLookups) {
    const table = resolveTable(graph, mapping, lookup.dimension);
    const name = table ? quoted(qualifiedTableName(table, defaults)) : quoted(lookup.dimension);
    const alias = `dim_${lookup.column}`;

    /**
     * The dimension's business key, surrogate and validity columns.
     *
     * The mapping that *builds* the dimension is authoritative, because that is where the
     * names are declared. But it is frequently not in scope, a conformed dimension is
     * shared across marts and is very often built by a different model than the one
     * loading this fact, so falling back to the dimension table's own columns is not a
     * nicety.
     *
     * **Getting this wrong is a silent fan-out.** Join a fact to a type-2 dimension
     * without a validity predicate and you get one row per historical version of every
     * customer, quietly multiplying every measure in the table. It does not error, it does
     * not look wrong on the diagram, and it is found in a report months later.
     */
    const source = mappingFor(graph, mapping.model, lookup.dimension);
    const dimensionColumns = new Set(table?.columns.map((column) => column.name) ?? []);
    const pick = (declared: string | undefined, ...candidates: string[]): string | undefined =>
      declared ?? candidates.find((candidate) => dimensionColumns.has(candidate));

    const businessKey = source?.dimensional?.businessKey?.[0] ?? lookup.sourceColumn;
    const surrogate = source?.dimensional?.surrogateKey ?? lookup.column;
    const validFrom = pick(source?.dimensional?.validFromColumn, "valid_from", "effective_from");
    const validTo = pick(source?.dimensional?.validToColumn, "valid_to", "effective_to");
    const currentFlag = pick(source?.dimensional?.currentFlagColumn, "is_current", "current_flag");

    const conditions = [`${alias}.${ident(businessKey)} = ${primary}.${ident(lookup.sourceColumn)}`];

    if (lookup.pointInTime && validFrom && eventTime) {
      conditions.push(`${alias}.${ident(validFrom)} <= ${primary}.${ident(eventTime)}`);
      if (validTo) {
        conditions.push(
          `(${alias}.${ident(validTo)} IS NULL OR ${alias}.${ident(validTo)} > ${primary}.${ident(eventTime)})`,
        );
      }
    } else if (currentFlag) {
      conditions.push(`${alias}.${ident(currentFlag)} = TRUE`);
    }

    /**
     * A point-in-time lookup that could not find validity columns.
     *
     * Say so in the SQL rather than emitting a join that looks fine and fans out. A
     * comment a reviewer sees is a far better outcome than a measure that is silently
     * double-counted, and it names the two ways to fix it.
     */
    if (lookup.pointInTime && !(validFrom && eventTime)) {
      joins.push(
        `-- WARNING: point-in-time lookup requested for \`${lookup.column}\`, but ${
          !eventTime
            ? "the mapping declares no watermarkColumn to use as the event time"
            : `no validity columns were found on \`${name}\``
        }.`,
        "--          Joining without one returns a row per historical version. Declare the",
        "--          dimension's validFromColumn/validToColumn, or set pointInTime: false.",
      );
    }

    joins.push(`LEFT JOIN ${name} AS ${alias}`);
    joins.push(`  ON ${conditions.join("\n  AND ")}`);

    /**
     * `COALESCE` onto the unknown-member key.
     *
     * A fact row whose dimension lookup misses must not vanish and must not carry NULL, * both silently drop it from any inner-joined report. Routing it to a designated
     * unknown member keeps the row countable and makes the miss visible.
     */
    const reference = `${alias}.${ident(surrogate)}`;
    columns.push(
      lookup.unknownMemberKey === undefined
        ? `${reference} AS ${ident(lookup.column)}`
        : `COALESCE(${reference}, ${typeof lookup.unknownMemberKey === "string" ? `'${lookup.unknownMemberKey}'` : lookup.unknownMemberKey}) AS ${ident(lookup.column)}`,
    );
  }

  return { joins, columns };
}

interface Defaults {
  project?: string;
  dataset?: string;
}

function resolveTable(graph: ObjectGraph, mapping: Mapping, ref: string): Table | undefined {
  const resolved = graph.resolve(ref, { model: mapping.model, kind: "table" })?.target.object;
  return resolved?.kind === "table" ? (resolved as Table) : undefined;
}

/**
 * The mapping that produces a given table, if this model builds it.
 *
 * `modelName` is optional because `model` is optional on every object: a mapping that
 * names no model cannot be searched within one, and returning undefined lets the caller
 * fall back to the lookup's own column names rather than crash on a degenerate model.
 */
function mappingFor(
  graph: ObjectGraph,
  modelName: string | undefined,
  targetRef: string,
): Mapping | undefined {
  if (!modelName) return undefined;
  const target = graph.resolve(targetRef, { model: modelName, kind: "table" })?.target.object;
  if (!target) return undefined;

  for (const entry of graph.inModel(modelName)) {
    if (entry.object.kind !== "mapping") continue;
    const candidate = entry.object as Mapping;
    const produced = graph.resolve(candidate.target, { model: modelName, kind: "table" })?.target.object;
    if (produced?.id === target.id) return candidate;
  }
  return undefined;
}

// ---------------------------------------------------------------- select

/** The SELECT every strategy is built from. */
function selectStatement(
  mapping: Mapping,
  graph: ObjectGraph,
  defaults: Defaults,
  extra: { columns?: string[]; where?: string[] } = {},
): string {
  const dim = mapping.dimensional;
  const lookupColumns = new Set(dim?.dimensionLookups.map((l) => l.column) ?? []);

  const columns = mapping.columnMappings
    // A column resolved by a dimension lookup is produced by the join, not by the mapping.
    .filter((cm) => !lookupColumns.has(cm.target))
    .map((cm) => `${columnExpression(cm)} AS ${ident(cm.target)}`);

  const { joins, columns: lookupSelects } = dimensionJoins(mapping, graph, defaults);
  const all = [...columns, ...lookupSelects, ...(extra.columns ?? [])];

  const lines: string[] = [];
  lines.push("SELECT");
  lines.push(all.map((column) => `  ${column}`).join(",\n"));
  lines.push(...fromClause(mapping, graph, defaults));
  lines.push(...joins);

  const where = [
    ...mapping.sources.map((source) => source.filter).filter((f): f is string => Boolean(f)),
    ...(mapping.where ? [mapping.where] : []),
    ...(extra.where ?? []),
  ];
  if (where.length > 0) lines.push(`WHERE ${where.join("\n  AND ")}`);

  if (mapping.groupBy.length > 0) lines.push(`GROUP BY ${mapping.groupBy.join(", ")}`);
  if (mapping.having) lines.push(`HAVING ${mapping.having}`);

  return lines.join("\n");
}

/** Business key expressions in *source* terms, for hashing before aliases exist. */
function businessKeyExpressions(mapping: Mapping, dim: DimensionalConfig): string[] {
  return dim.businessKey.map((key) => {
    const cm = mapping.columnMappings.find((entry) => entry.target === key);
    return cm ? columnExpression(cm) : key;
  });
}

/**
 * The incremental predicate.
 *
 * Compares against the target's own high-water mark rather than a fixed date, so a
 * pipeline that has not run for a week catches up on its own. `lookbackDays` re-processes
 * a trailing window because source rows arrive late, and a strict `>` would skip anything
 * that landed after the previous run read the table.
 */
function incrementalWhere(mapping: Mapping, dim: DimensionalConfig | undefined): string | undefined {
  const watermark = dim?.watermarkColumn;
  if (!watermark) return undefined;

  const alias = mapping.sources[0]?.alias ?? "s";
  const lookback = dim?.lookbackDays ?? 0;
  const floor =
    lookback > 0
      ? `DATE_SUB(MAX(${ident(watermark)}), INTERVAL ${lookback} DAY)`
      : `MAX(${ident(watermark)})`;

  return `${alias}.${ident(watermark)} >= (SELECT ${floor} FROM ${SELF})`;
}

// ---------------------------------------------------------------- strategies

/**
 * Slowly-changing dimension, type 2, the reason this generator exists.
 *
 * Emitted as `type: "operations"` because the correct load is **two statements** and no
 * single BigQuery `MERGE` can do it: a merge applies at most one action per matched row,
 * and a changed business key needs both its current row closed *and* a new row opened.
 * Attempting it as one statement is the single most common way hand-written SCD2 goes
 * wrong, it silently keeps the old values or leaves two rows flagged current.
 *
 * So: close first, then insert. The insert's `LEFT JOIN ... WHERE IS NULL` picks up both
 * genuinely new keys and the keys the merge just closed, which is why the order matters
 * and why they cannot be swapped.
 */
function scd2Statements(
  mapping: Mapping,
  graph: ObjectGraph,
  defaults: Defaults,
  dim: DimensionalConfig,
): string[] {
  const validFrom = dim.validFromColumn ?? "valid_from";
  const validTo = dim.validToColumn ?? "valid_to";
  const currentFlag = dim.currentFlagColumn ?? "is_current";
  const hashColumn = dim.hashColumn ?? "change_hash";

  const tracked = changeTrackedColumns(mapping);
  const trackedExpressions = tracked.map((name) => {
    const cm = mapping.columnMappings.find((entry) => entry.target === name);
    return `CAST(${cm ? columnExpression(cm) : name} AS STRING)`;
  });
  const hashExpression =
    trackedExpressions.length > 0
      ? `FARM_FINGERPRINT(CONCAT(${trackedExpressions.join(", '|', ")}))`
      : "0";

  const businessKeys = businessKeyExpressions(mapping, dim);
  const surrogate = dim.surrogateKey;
  const surrogateExpression = surrogate
    ? surrogateKeyExpression(dim, businessKeys, { versioned: true, validFrom: "CURRENT_TIMESTAMP()" })
    : "";

  // The staged source: every mapped column plus the audit columns the strategy owns.
  const audit = [
    `${hashExpression} AS ${ident(hashColumn)}`,
    ...(surrogate && surrogateExpression ? [`${surrogateExpression} AS ${ident(surrogate)}`] : []),
  ];
  const staged = selectStatement(mapping, graph, defaults, { columns: audit });

  const keyJoin = dim.businessKey
    .map((key) => `target.${ident(key)} = source.${ident(key)}`)
    .join("\n    AND ");

  const inserted = [
    ...mapping.columnMappings.map((cm) => cm.target),
    ...(surrogate ? [surrogate] : []),
    hashColumn,
    validFrom,
    validTo,
    currentFlag,
  ];

  const expire = [
    "-- 1. Close the current row of every business key whose tracked columns changed.",
    "--    Runs first so the insert below can find those keys as \"no current row\".",
    `MERGE ${SELF} AS target`,
    "USING (",
    indent(staged, "  "),
    ") AS source",
    `ON ${keyJoin}`,
    `    AND target.${ident(currentFlag)} = TRUE`,
    `WHEN MATCHED AND target.${ident(hashColumn)} != source.${ident(hashColumn)} THEN UPDATE SET`,
    `  ${ident(validTo)} = CURRENT_TIMESTAMP(),`,
    `  ${ident(currentFlag)} = FALSE`,
  ].join("\n");

  const insert = [
    "-- 2. Open a new version for every key with no current row: brand new keys, and the",
    "--    keys step 1 just closed.",
    `INSERT INTO ${SELF} (${inserted.map(ident).join(", ")})`,
    "SELECT",
    `  ${[...mapping.columnMappings.map((cm) => `source.${ident(cm.target)}`), ...(surrogate ? [`source.${ident(surrogate)}`] : []), `source.${ident(hashColumn)}`].join(",\n  ")},`,
    `  CURRENT_TIMESTAMP() AS ${ident(validFrom)},`,
    `  CAST(NULL AS TIMESTAMP) AS ${ident(validTo)},`,
    `  TRUE AS ${ident(currentFlag)}`,
    "FROM (",
    indent(staged, "  "),
    ") AS source",
    `LEFT JOIN ${SELF} AS target`,
    `  ON ${keyJoin}`,
    `  AND target.${ident(currentFlag)} = TRUE`,
    `WHERE target.${ident(dim.businessKey[0] ?? "id")} IS NULL`,
  ].join("\n");

  return [expire, insert];
}

function indent(text: string, prefix: string): string {
  return text
    .split("\n")
    .map((line) => (line.length > 0 ? prefix + line : line))
    .join("\n");
}

